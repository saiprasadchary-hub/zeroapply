import assert from 'node:assert/strict';
import { ApplicationLogger } from '../src/agent/tracker/applicationLogger';
let updates = 0;
const unsubscribe = ApplicationLogger.subscribe(() => { updates++; });
const jobUrl = 'https://www.linkedin.com/jobs/view/123456';
ApplicationLogger.log({ portal: 'LinkedIn', jobTitle: 'Intern', companyName: 'Acme', status: 'PARTIAL', jobUrl });
assert.equal(ApplicationLogger.hasSubmitted({ jobUrl }), false);
ApplicationLogger.log({ portal: 'LinkedIn', jobTitle: 'Intern', companyName: 'Acme', status: 'SUCCESS', jobUrl });
assert.equal(updates, 3);
assert.equal(ApplicationLogger.hasSubmitted({ jobUrl: 'https://www.linkedin.com/jobs/search/?currentJobId=123456&trk=test' }), true);
assert.equal(ApplicationLogger.hasSubmitted({ jobUrl: 'https://www.linkedin.com/jobs/view/987654', jobTitle: 'Intern', companyName: 'Acme', portal: 'LinkedIn' }), false);
const count = ApplicationLogger.getLogs().length;
ApplicationLogger.log({ portal: 'LinkedIn', status: 'SUCCESS', jobUrl: jobUrl + '?trk=again' });
assert.equal(ApplicationLogger.getLogs().length, count);
ApplicationLogger.log({ portal: 'Google Forms', status: 'SUCCESS', jobUrl: 'https://example.com/jobs/42', url: 'https://docs.google.com/forms/d/e/abc/viewform?pli=1' });
assert.equal(ApplicationLogger.hasSubmitted({ jobUrl: 'https://docs.google.com/forms/d/e/abc/viewform?usp=sharing' }), true);
assert.equal(ApplicationLogger.hasSubmitted({ jobTitle: 'Intern', companyName: 'Acme', portal: 'LinkedIn' }), true);
assert.equal(ApplicationLogger.hasSubmitted({ jobTitle: 'Intern', companyName: 'Other', portal: 'LinkedIn' }), false);
unsubscribe();
console.log('Dashboard updates and duplicate application checks passed');
