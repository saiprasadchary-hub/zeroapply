import assert from 'node:assert/strict';
import vm from 'node:vm';
import { executeSyntheticInteraction } from '../src/agent/domScanner/syntheticInteraction';
let clicks = 0;
const checkbox = { tagName: 'INPUT', type: 'checkbox', checked: false, disabled: false, getAttribute: () => null, click: (): void => { clicks++; checkbox.checked = !checkbox.checked; }, dispatchEvent: (): void => {} };
const context = vm.createContext({ window: {}, setTimeout, Event, document: { querySelector: () => checkbox } });
const bridge = { executeJavaScript: async (script: string): Promise<unknown> => structuredClone(await vm.runInContext(script, context)) };
assert.equal((await executeSyntheticInteraction(bridge, 'checkbox', '#joined', 'true')).success, true);
assert.equal(checkbox.checked, true);
assert.equal((await executeSyntheticInteraction(bridge, 'checkbox', '#joined', 'true')).success, true);
assert.equal(clicks, 1);
assert.equal((await executeSyntheticInteraction(bridge, 'checkbox', '#joined', 'false')).success, true);
assert.equal(checkbox.checked, false);
checkbox.disabled = true;
assert.equal((await executeSyntheticInteraction(bridge, 'checkbox', '#joined', 'true')).success, false);
checkbox.disabled = false;
checkbox.click = (): void => { clicks++; };
assert.equal((await executeSyntheticInteraction(bridge, 'checkbox', '#joined', 'true')).success, false);
console.log('Checkbox persistence checks passed');
